export type PixelGlyphName = keyof typeof PIXEL_GLYPHS;

/** 单个像素图标的 props：尺寸为**已解析的数值**（Icon 负责档位 → 数值）。 */
export interface PixelGlyphProps extends Omit<SVGProps<SVGSVGElement>, 'color'> {
  /** 边长（px），默认 16。 */
  size?: number;
  /** 语义色；缺省继承 currentColor。 */
  color?: string;
}

interface RenderedCell {
  readonly x: number;
  readonly y: number;
  readonly width: number;
  readonly tone: number;
}

/** 行内同档相邻格合并成一条 rect（硬边像素画的等价简化，减少 DOM 节点）。 */
function scanRuns(grid: readonly string[]): RenderedCell[] {
  const runs: RenderedCell[] = [];
  for (let y = 0; y < grid.length; y += 1) {
    const row = grid[y] ?? '';
    let x = 0;
    while (x < row.length) {
      const ch = row[x] ?? '.';
      const tone = GLYPH_TONES[ch as keyof typeof GLYPH_TONES];
      if (tone === undefined) {
        x += 1;
        continue;
      }
      let end = x;
      while (end + 1 < row.length && row[end + 1] === ch) end += 1;
      runs.push({ x, y, width: end - x + 1, tone });
      x = end + 1;
    }
  }
  return runs;
}

function cellRect(cell: RenderedCell, key: string): ReactNode {
  return (
    <rect
      key={key}
      x={cell.x}
      y={cell.y}
      width={cell.width}
      height={1}
      fill="currentColor"
      opacity={TONE_OPACITY[cell.tone as keyof typeof TONE_OPACITY]}
    />
  );
}

function svgProps(size: number | undefined, color: string | undefined, className: string | undefined): SVGProps<SVGSVGElement> {
  const px = size ?? PIXEL_GLYPH_GRID;
  return {
    xmlns: 'http://www.w3.org/2000/svg',
    viewBox: `0 0 ${String(PIXEL_GLYPH_GRID)} ${String(PIXEL_GLYPH_GRID)}`,
    width: px,
    height: px,
    color,
    shapeRendering: 'crispEdges',
    focusable: 'false',
    className: clsx('sc-icon', className),
  };
}

/** 普通 glyph 组件工厂：整枚 glyph 一组 rect。 */
function makeGlyph(name: PixelGlyphName) {
  const runs = scanRuns(PIXEL_GLYPHS[name]);
  function PixelGlyph({ size, color, className, ...rest }: PixelGlyphProps) {
    return (
      <svg {...rest} {...svgProps(size, color, className)}>
        {runs.map((cell) => cellRect(cell, `${String(cell.y)}-${String(cell.x)}`))}
      </svg>
    );
  }
  PixelGlyph.displayName = `Pixel${name}`;
  return PixelGlyph;
}

/** 两态 glyph（AiRobot）：眼部/天线单独成组，供 CSS 按开合态切换明暗。 */
export const AI_ROBOT_EYE_CLASS = 'sc-icon__eye';
export const AI_ROBOT_ANTENNA_CLASS = 'sc-icon__antenna';

function makeAiRobot() {
  const runs = scanRuns(PIXEL_GLYPHS.AiRobot);
  const isEye = (c: RenderedCell): boolean =>
    AI_ROBOT_EYE.rows.includes(c.y) && c.x >= AI_ROBOT_EYE.fromX && c.x + c.width - 1 <= AI_ROBOT_EYE.toX;
  const isAntenna = (c: RenderedCell): boolean => AI_ROBOT_ANTENNA.rows.includes(c.y);
  const eyes = runs.filter(isEye);
  const antenna = runs.filter(isAntenna);
  const body = runs.filter((c) => !isEye(c) && !isAntenna(c));

  function AiRobot({ size, color, className, ...rest }: PixelGlyphProps) {
    return (
      <svg {...rest} {...svgProps(size, color, className)}>
        {body.map((cell) => cellRect(cell, `${String(cell.y)}-${String(cell.x)}`))}
        <g className={AI_ROBOT_ANTENNA_CLASS}>{antenna.map((cell) => cellRect(cell, `a${String(cell.y)}-${String(cell.x)}`))}</g>
        <g className={AI_ROBOT_EYE_CLASS}>{eyes.map((cell) => cellRect(cell, `e${String(cell.y)}-${String(cell.x)}`))}</g>
      </svg>
    );
  }
  AiRobot.displayName = 'PixelAiRobot';
  return AiRobot;
}

